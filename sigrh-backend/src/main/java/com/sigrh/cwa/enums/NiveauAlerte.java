package com.sigrh.cwa.enums;

/**
 * Énumération des niveaux de sévérité des alertes RH.
 * 
 * - FAIBLE: Alerte peu importante, information
 * - MOYEN: Alerte modérée, nécessite attention
 * - ELEVE: Alerte importante, action recommandée
 * - CRITIQUE: Alerte critique, action urgent requise
 * 
 * @author Équipe SIGRH
 * @version 1.0
 */
public enum NiveauAlerte {
    FAIBLE,
    MOYEN,
    ELEVE,
    CRITIQUE
}
